#!/usr/bin/env python3
"""Debug plan Stage 0: the reference numbers (Tier 1 Snake and SK_R0_D0,
PAPER_V100, 1B), read from the all-versions workbook, with its Block 3
metric definitions (docs/snake/results/debug/S0_reference.md).

    PYTHONPATH=<dir with openpyxl> python3 util/snake/debug/s0_reference.py [<xlsx>]
"""
import os
import sys

from openpyxl import load_workbook

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
XLSX = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "docs", "snake", "results",
                                                          "Snake_all_versions_2026-10-28.xlsx")
COLS = ["IPC gain vs no prefetching (%)", "Perfect-L1 ceiling (%)", "Coverage, Snake-paper style (coverage_pred, %)",
        "Delivered coverage (timely + late) / demand (%)", "Accuracy, Snake-paper style (timely / demand, %)",
        "Prefetches issued per demand sector", "Unused share of issued (%)", "L1 hit rate, baseline (%)",
        "L1 hit rate, version (%)", "SnakeCharmer accuracy H/F (%)", "On time (%)", "Too late (%)",
        "Best kernel IPC / same kernel without prefetching (Diagnostic)"]
SHORT = ["IPC gain", "perfect-L1", "predicted (coverage_pred)", "timely + late / demand", "timely / demand",
         "issued / demand", "unused of issued", "L1 hit base", "L1 hit Snake", "accuracy H/F", "on time", "too late",
         "best kernel ratio (diagnostic)"]


def fmt(v, col):
    if isinstance(v, float):
        return "%.4f" % v if "ratio" in col or "Diagnostic" in col else ("%+.2f" % v if "gain" in col or "ceiling" in col
                                                                       else "%.2f" % v)
    return "n/a" if v in (None, "") else str(v).replace("n/a: not collected in this build", "n/a (old build)")


def main():
    ws = load_workbook(XLSX, data_only=True)["Snake_results"]
    rows = [[c.value for c in r] for r in ws.iter_rows()]
    h = next(i for i, r in enumerate(rows) if r[0] == "Version" and r[1] == "GPU setup")
    hdr = rows[h]
    ix = [hdr.index(c) for c in COLS]
    out = ["# Debug plan Stage 0: reference numbers (2026-10-29)\n",
           "Source: `%s` (generated by `util/snake/make_all_versions_xlsx.py`), read by "
           "`util/snake/debug/s0_reference.py`. PAPER_V100, 1B instructions. Gains and rates in %%; "
           "means as defined in Block 3 below.\n" % os.path.relpath(XLSX, ROOT)]
    for ver in ("Tier 1 Snake", "SK_R0_D0"):
        out.append("## %s\n" % ver)
        out.append("| workload | " + " | ".join(SHORT) + " |")
        out.append("|---|" + "---|" * len(SHORT))
        for r in rows[h + 1:]:
            if r[0] != ver or r[1] != "PAPER_V100" or r[2] != "1B":
                continue
            if r[6] == "Diagnostic" or (str(r[3]).startswith("GMEAN") and "7 apps" not in str(r[3])):
                continue
            name = "**%s**" % r[3].replace("GMEAN / mean: ", "") if str(r[3]).startswith("GMEAN") else r[3]
            out.append("| %s | %s |" % (name, " | ".join(fmt(r[i], c) for i, c in zip(ix, COLS))))
        bk = next((r for r in rows[h + 1:] if r[0] == ver and r[1] == "PAPER_V100" and r[2] == "1B"
                   and str(r[3]).startswith("GMEAN best-kernel ratio (Diagnostic): our 7 apps")), None)
        if bk:
            out.append("\nBest-kernel GMEAN over the 7 apps (diagnostic only): %.4f.\n" % bk[ix[-1]])
    i = next(k for k, r in enumerate(rows) if r[0] == "BLOCK 3: METRIC DEFINITIONS AND NOTES")
    out.append("## Metric definitions (Block 3 of the workbook)\n")
    out.append("| item | definition | source |")
    out.append("|---|---|---|")
    for r in rows[i + 2:]:
        if r[0] in (None, "Settings checks (tokens and docs vs effective options)"):
            break
        out.append("| %s | %s | %s |" % (r[0], str(r[1]).replace("|", "/"), r[2] or ""))
    print("\n".join(out))


if __name__ == "__main__":
    main()
