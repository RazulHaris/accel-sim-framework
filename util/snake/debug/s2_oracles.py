#!/usr/bin/env python3
"""Debug plan Stage 2: oracle upper bounds and Gate G2
(docs/snake/results/debug/S2_oracles.md).

    s2_oracles.py

PAPER_V100, 1B, corrected decoder, 9 workloads.  Whole-run IPC gain
(gpu_tot_ipc / baseline - 1) against the Tier 1 baseline (sim_run_baseline)
for: Tier 1 Snake (sim_run_snake), O-TIME and O-PRED (Tier 1 Snake with
-snake_oracle_time / -snake_oracle_pred, sim_run_snake_debug/s1s2), and
perfect L1 (sim_run_snake_gate/D1_pl1d).  GMEAN over the 7 apps, an app's
inputs combined first (geometric), as in final_tier1.md.
  O-TIME  every prefetch Snake issues fills the L1D at its next cycle; a copy
          still goes to memory for the traffic and its response is dropped
  O-PRED  every predicted sector, issued or not, is installed the same way
Gate G2: O-TIME >= Tier 1 + 3 GMEAN points, or + 10 points on some app;
O-PRED >= O-TIME + 3 GMEAN points.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
from kernel_gap import gm, gm_apps, done, tot_ipc  # noqa: E402
import make_report_xlsx as R  # noqa: E402

P1 = "QV100-SASS-PAPER_V100-1B_INSN"
S = P1 + "-SNAKE-SNAKE_FP1"
BASE = ("sim_run_baseline", P1)
VERS = [("Tier 1 Snake", "sim_run_snake", S), ("O-TIME", "sim_run_snake_debug/s1s2", S + "-ORACLE_TIME"),
        ("O-PRED", "sim_run_snake_debug/s1s2", S + "-ORACLE_PRED"),
        ("perfect L1", "sim_run_snake_gate/D1_pl1d", P1 + "-PERFECT_L1D")]


def sim(d, a, g, c):
    return os.path.join(ROOT, d, "runs", a, g, c, "sim.out")


def counters(p):
    t = open(p, errors="replace").read()
    return {k: int(v) for k, v in re.findall(r"^snake_(\w+) = (\d+)\s*$", t, re.M)}


def f(x, d=1, sign=True):
    return "n/a" if x is None else ("%+.*f" if sign else "%.*f") % (d, x)


def main():
    WL = R.workloads()
    gains = {v: {} for v, _, _ in VERS}
    extra = {}
    for a, g in WL:
        b = sim(BASE[0], a, g, BASE[1])
        for v, d, c in VERS:
            p = sim(d, a, g, c)
            gains[v][(R.app_of(a), g)] = (tot_ipc(p) / tot_ipc(b) - 1) * 100 if done(p) and done(b) else None
            if v.startswith("O-") and done(p):
                extra[(v, a, g)] = counters(p)
    out = ["# Debug plan Stage 2: oracle upper bounds (PAPER_V100, 1B, corrected decoder)\n",
           "Generated by `util/snake/debug/s2_oracles.py`. Whole-run IPC gain vs no prefetching, %. "
           "Build of the oracle runs: accel-sim `bc03386` + gpgpu-sim `37846351`.\n",
           "| workload | " + " | ".join(v for v, _, _ in VERS) + " |", "|---|" + "---|" * len(VERS)]
    for a, g in WL:
        out.append("| %s | %s |" % (R.wl_label(a, g), " | ".join(f(gains[v][(R.app_of(a), g)]) for v, _, _ in VERS)))
    gmean = {v: gm_apps(gains[v]) for v, _, _ in VERS}
    out.append("| **GMEAN, 7 apps** | %s |" % " | ".join("**%s**" % f(gmean[v]) for v, _, _ in VERS))
    out += ["\nOracle mechanics per workload (whole run): prefetches issued per demand sector, timely uses and "
            "late merges per demand sector (%), installs that found the sector already present or no line, and "
            "memory copies dropped because the miss queue was full.\n",
            "| workload | oracle | issued / demand | timely / demand | late / demand | installs | install: already "
            "present | install: no line or MSHR | copies sent | copies dropped (miss queue full) |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    for a, g in WL:
        for v in ("O-TIME", "O-PRED"):
            s = extra.get((v, a, g))
            if not s:
                continue
            dem = s.get("demand_sector_accesses", 0) or 1
            out.append("| %s | %s | %.2f | %.1f | %.1f | %d | %d | %d | %d | %d |" % (
                R.wl_label(a, g), v, s.get("pf_issued", 0) / dem, 100.0 * s.get("pf_useful_timely", 0) / dem,
                100.0 * s.get("pf_late", 0) / dem, s.get("oracle_installs", 0), s.get("oracle_install_dup", 0),
                s.get("oracle_install_fail", 0), s.get("oracle_ghost_sent", 0), s.get("oracle_ghost_dropped", 0)))
    t1, ot, op = gmean["Tier 1 Snake"], gmean["O-TIME"], gmean["O-PRED"]
    per_app = {}
    for (ap, g), v in gains["O-TIME"].items():
        t = gains["Tier 1 Snake"].get((ap, g))
        if v is not None and t is not None:
            per_app[ap] = max(per_app.get(ap, -1e9), v - t)
    if None not in (t1, ot, op):
        best = max(per_app.items(), key=lambda kv: kv[1])
        g_time = ot - t1 >= 3 or best[1] >= 10
        g_pred = op - ot >= 3
        out += ["\n## Gate G2\n",
                "- O-TIME vs Tier 1: %+.2f GMEAN points; largest per-workload gap %+.1f points (%s). "
                "Timeliness fixes: **%s**." % (ot - t1, best[1], best[0], "worth pursuing" if g_time else "not worth pursuing"),
                "- O-PRED vs O-TIME: %+.2f GMEAN points. Issue-loss fixes: **%s**." % (
                    op - ot, "worth pursuing" if g_pred else "not worth pursuing")]
        if not g_time and not g_pred:
            out.append("- Both fail: Snake's own predictions cannot produce large gains in this environment. "
                       "Stages 3-5 only rule out bugs; Stage 6 skips the extensions (plan, Gate G2).")
    else:
        out.append("\nGate G2: pending (runs missing).")
    print("\n".join(out))


if __name__ == "__main__":
    main()
